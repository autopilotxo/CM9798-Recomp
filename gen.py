"""gen.py - generate C for every function found by disasm.py.
usage: python3 gen.py <workdir with disasm.json+fixups.txt> <outdir>"""
import json, sys, os, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lift import Fn

W, OUT = sys.argv[1], sys.argv[2]
SHIFT = int(sys.argv[3], 16) if len(sys.argv) > 3 else 0
os.makedirs(OUT, exist_ok=True)
d = json.load(open(os.path.join(W, 'disasm.json')))
ins = {int(k): v for k, v in d['ins'].items()}
funcs = {int(k): v for k, v in d['funcs'].items()}
jtabs = {int(k): v for k, v in d['jtabs'].items()}
fix = {}
for l in open(os.path.join(W, 'fixups.txt')):
    s_, t_ = l.split(' -> '); fix[int(s_, 16)] = int(t_, 16)
funcset = set(funcs)
# hand-written replacements: generated code becomes f_XXXXXX_orig
overrides = set()
_ovf = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'overrides.txt')
if os.path.exists(_ovf):
    for l in open(_ovf):
        l = l.split('#')[0].strip()
        if l: overrides.add(int(l.split()[0], 16) + SHIFT)
# single-instruction patches: <addr> replace|after <C statement>
patches = {}; hooks = set()
_pf = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'patches.txt')
if os.path.exists(_pf):
    import re as _re0
    for l in open(_pf):
        l = l.split('#')[0].strip()
        if not l: continue
        a_, kind, stmt = l.split(None, 2)
        assert kind in ('replace', 'after'), l
        patches[int(a_, 16) + SHIFT] = (kind, stmt)
        hooks.update(_re0.findall(r'([A-Za-z_]\w*)\s*\(', stmt))   # hook_*: void, others return uint32_t

def apply_patches(code):
    lines = code.split('\n')
    for i, ln in enumerate(lines):
        st = ln.lstrip()
        if not st.startswith('/* '): continue
        try: a_ = int(st[3:st.index(':')], 16)
        except ValueError: continue
        if a_ not in patches: continue
        kind, stmt = patches[a_]
        head = ln[:ln.index('*/') + 2]
        lines[i] = (f'{head} {stmt}  /* patched */' if kind == 'replace'
                    else f'{ln} {stmt}  /* patched */')
        applied.add(a_)
    return '\n'.join(lines)
applied = set()
# relocations.txt: data moved to a bigger home (relocate.py)
import relocate as _reloc
_moves, _imms = _reloc.load()

names = {}
lab = os.path.join(W, 'labels.csv')
if os.path.exists(lab):
    for l in open(lab):
        a, n = l.strip().split(',', 1); names[int(a, 16) + SHIFT] = n

with open(os.path.join(OUT, 'funcs.h'), 'w') as h:
    h.write('/* generated */\n#pragma once\n#include "rt.h"\n')
    for hk in sorted(h_ for h_ in hooks if not h_.isupper()):          # all-caps names are macros
        h.write(f'{"void" if hk.startswith("hook_") else "uint32_t"} {hk}(void);  /* patches.txt, rt/ */\n')
    for f in sorted(funcs):
        h.write(f'void f_{f:06x}(void);' + (f' /* {names[f]} */' if f in names else '') + '\n')
        if f in overrides: h.write(f'void f_{f:06x}_orig(void);  /* generated original, overridden in rt/overrides.c */\n')

unsup = collections.Counter(); per_file = 60; files = []
order = sorted(funcs)
for i in range(0, len(order), per_file):
    fn = os.path.join(OUT, f'game_{i // per_file:03d}.c'); files.append(fn)
    with open(fn, 'w') as c:
        c.write('/* generated by gen.py from CM2E16.EXE - do not edit, override in hand/ instead */\n#include "funcs.h"\n')
        c.write('#pragma GCC diagnostic ignored "-Wunused-label"\n#pragma GCC diagnostic ignored "-Wunused-variable"\n#pragma GCC diagnostic ignored "-Wunused-but-set-variable"\n\n')
        for f in order[i:i + per_file]:
            F = Fn(f, funcs[f], ins, funcset, jtabs, fix)
            if f in names: c.write(f'/* {names[f]} */\n')
            code = F.emit()
            if patches: code = apply_patches(code)
            code = _reloc.relocate_code(code, _moves, _imms)
            if f in overrides: code = code.replace(f'void f_{f:06x}(void) {{', f'void f_{f:06x}_orig(void) {{', 1)
            c.write(code + '\n\n')
            unsup.update(F.unsup)

with open(os.path.join(OUT, 'functable.c'), 'w') as t:
    t.write('/* generated */\n#include "funcs.h"\n#include "rt_internal.h"\n')
    t.write('const struct gfunc g_funcs[] = {\n')
    for f in order: t.write(f'  {{0x{f:x}u, f_{f:06x}}},\n')
    t.write('};\nconst unsigned g_nfuncs = %d;\n' % len(order))

# return-site table: address after every call instruction
import re as _re
rets = sorted({a + ins[a][0] for a in ins if _re.search(r'(^|\s)call$', ins[a][1])})
with open(os.path.join(OUT, 'retsites.c'), 'w') as t:
    t.write('/* generated: addresses following a call instruction */\n#include <stdint.h>\n')
    t.write('const uint32_t g_retsites[] = {\n' + ''.join(f'0x{r:x}u,\n' for r in rets) + '};\n')
    t.write('const unsigned g_nretsites = %d;\n' % len(rets))
missing = set(patches) - applied
if missing: sys.exit('patches.txt: no instruction at ' + ', '.join(f'{m - SHIFT:06x}' for m in sorted(missing)))
print('patched', len(applied), 'instructions')
print('functions', len(funcs), 'C files', len(files), 'return sites', len(rets), 'overridden', len(overrides))
print('unsupported/errored instruction kinds:', sum(unsup.values()))
for k, v in unsup.most_common(40): print(f'  {v:5d} {k}')
